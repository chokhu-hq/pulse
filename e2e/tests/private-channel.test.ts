import { afterEach, describe, expect, it } from "vitest";
import {
  disconnectAll,
  expectNoEvent,
  makeClient,
  makeServerClient,
  subscribeAndWait,
  waitForConnection,
  waitForEvent,
  type PusherClient,
} from "../src/clients.js";

describe("private channels", () => {
  const server = makeServerClient();
  let clients: PusherClient[] = [];

  afterEach(async () => {
    await disconnectAll(...clients);
    clients = [];
  });

  it("subscribes with a server-SDK signature and receives events", async () => {
    const client = makeClient();
    clients.push(client);
    await waitForConnection(client);

    // Auth is generated by the official server SDK inside makeClient's
    // channelAuthorization handler — a true 1:1 signing-scheme check.
    const channel = await subscribeAndWait(client, "private-room");

    const payload = { secret: "shhh", at: 123 };
    const received = waitForEvent<typeof payload>(channel, "update");
    await server.trigger("private-room", "update", payload);
    expect(await received).toEqual(payload);
  });

  it("rejects a subscription with an invalid signature", async () => {
    const client = makeClient({ badAuth: true });
    clients.push(client);
    await waitForConnection(client);

    const channel = client.subscribe("private-bad");
    // pulse must not confirm a subscription signed with a bad signature.
    await expectNoEvent(channel, "pusher:subscription_succeeded", 1500);
  });
});
